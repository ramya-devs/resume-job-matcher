def create_pdf_report(
    final_score,
    semantic_score,
    skill_percentage,
    experience_match,
    matched_skills,
    missing_skills,
    recommendations,
    evidence,
    ats_result=None,
):
    """Create a professional PDF analysis report in memory."""
    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title="Resume Job Match Analysis Report",
        author="Resume Job Match Analyzer",
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Title"],
        fontSize=22,
        leading=27,
        alignment=TA_CENTER,
        spaceAfter=8,
    )

    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        fontSize=10,
        leading=14,
        alignment=TA_CENTER,
        textColor=colors.grey,
        spaceAfter=18,
    )

    heading_style = ParagraphStyle(
        "ReportHeading",
        parent=styles["Heading2"],
        fontSize=15,
        leading=19,
        spaceBefore=12,
        spaceAfter=8,
    )

    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["BodyText"],
        fontSize=10,
        leading=14,
        spaceAfter=5,
    )

    small_style = ParagraphStyle(
        "ReportSmall",
        parent=styles["BodyText"],
        fontSize=8.5,
        leading=12,
        textColor=colors.grey,
    )

    story = []

    story.append(Paragraph("Resume → Job Match Analysis", title_style))
    story.append(
        Paragraph(
            "Generated by Resume → Job Match Analyzer",
            subtitle_style,
        )
    )

    # Score table
    score_data = [
        ["Final Match Score", "Semantic Similarity", "Skill Coverage"],
        [
            f"{float(final_score):.2f}%",
            f"{float(semantic_score):.2f}%",
            f"{float(skill_percentage):.1f}%",
        ],
    ]

    score_table = Table(
        score_data,
        colWidths=[55 * mm, 55 * mm, 55 * mm],
    )
    score_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EAF2FF")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#17365D")),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTNAME", (0, 1), (-1, 1), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 10),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
                ("TOPPADDING", (0, 0), (-1, -1), 9),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
            ]
        )
    )
    story.append(score_table)
    story.append(Spacer(1, 8))

    story.append(Paragraph("Experience Match", heading_style))
    story.append(Paragraph(escape(str(experience_match)), body_style))

    story.append(Paragraph("Matched Skills", heading_style))
    if matched_skills:
        for skill in matched_skills:
            story.append(Paragraph(f"✓ {escape(str(skill))}", body_style))
    else:
        story.append(Paragraph("No matching skills detected.", body_style))

    story.append(Paragraph("Missing Skills", heading_style))
    if missing_skills:
        for skill in missing_skills:
            story.append(Paragraph(f"✗ {escape(str(skill))}", body_style))
    else:
        story.append(Paragraph("No major missing skills detected.", body_style))

    story.append(Paragraph("Skill Evidence", heading_style))
    if evidence:
        for skill in matched_skills:
            text = evidence.get(skill)
            if text:
                story.append(
                    KeepTogether(
                        [
                            Paragraph(
                                f"<b>{escape(str(skill))}</b>",
                                body_style,
                            ),
                            Paragraph(
                                f"Resume evidence: {escape(str(text))}",
                                small_style,
                            ),
                            Spacer(1, 4),
                        ]
                    )
                )
    else:
        story.append(Paragraph("No evidence available.", body_style))

    story.append(Paragraph("Suggested Improvements", heading_style))
    if recommendations:
        for index, recommendation in enumerate(recommendations, start=1):
            story.append(
                Paragraph(
                    f"<b>{index}.</b> {escape(str(recommendation))}",
                    body_style,
                )
            )
    else:
        story.append(
            Paragraph(
                "Your resume already covers the major requirements of this job.",
                body_style,
            )
        )

    if ats_result:
        story.append(Paragraph("ATS Compatibility", heading_style))
        story.append(Paragraph(
            f"ATS heuristic score: {float(ats_result['score']):.1f}% ({escape(str(ats_result['status']))})",
            body_style,
        ))
        story.append(Paragraph(
            f"Job-specific keyword coverage: {float(ats_result['keyword_coverage']):.1f}%",
            body_style,
        ))
        if ats_result.get("missing_keywords"):
            story.append(Paragraph(
                "Missing ATS keywords: " + escape(", ".join(ats_result["missing_keywords"])),
                body_style,
            ))
        if ats_result.get("improvements"):
            story.append(Paragraph("ATS Improvements", body_style))
            for index, item in enumerate(ats_result["improvements"], start=1):
                story.append(Paragraph(
                    f"<b>{index}.</b> {escape(str(item))}",
                    body_style,
                ))

    story.append(Paragraph("Score Breakdown", heading_style))
    breakdown_data = [
        ["Component", "Score", "Weight"],
        ["Semantic Similarity", f"{float(semantic_score):.2f}%", "60%"],
        ["Skill Coverage", f"{float(skill_percentage):.1f}%", "30%"],
        [
            "Experience",
            f"{100 if experience_match == 'Good' else 60 if experience_match == 'Moderate' else 30}%",
            "10%",
        ],
    ]

    breakdown_table = Table(
        breakdown_data,
        colWidths=[75 * mm, 45 * mm, 45 * mm],
    )
    breakdown_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F2F2F2")),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.lightgrey),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("TOPPADDING", (0, 0), (-1, -1), 7),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
            ]
        )
    )
    story.append(breakdown_table)
    story.append(Spacer(1, 12))

    story.append(
        Paragraph(
            "Built with Python · Sentence Transformers · Scikit-learn · PyMuPDF · Streamlit",
            small_style,
        )
    )

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()


