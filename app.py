def analyze_ats(resume_text, job_description, jd_skills):
    """Heuristic ATS analysis for resume structure and job-specific keywords."""
    import re

    text = resume_text or ""
    lower_text = text.lower()

    section_aliases = {
        "Contact Information": ["email", "phone", "linkedin", "github"],
        "Summary / Objective": ["summary", "objective", "profile"],
        "Skills": ["skills", "technical skills", "technologies"],
        "Experience": ["experience", "internship", "employment", "work experience"],
        "Projects": ["projects", "project experience"],
        "Education": ["education", "academic", "qualification"],
    }

    section_results = {
        section: any(alias in lower_text for alias in aliases)
        for section, aliases in section_aliases.items()
    }

    contact_checks = {
        "Email": bool(re.search(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}", text)),
        "Phone": bool(re.search(r"(?:\+?\d[\d\s().-]{8,}\d)", text)),
        "LinkedIn": "linkedin.com" in lower_text,
        "GitHub": "github.com" in lower_text,
    }

    required_keywords = list(dict.fromkeys(jd_skills or []))
    matched_keywords = [s for s in required_keywords if s.lower() in lower_text]
    missing_keywords = [s for s in required_keywords if s.lower() not in lower_text]

    keyword_coverage = (
        len(matched_keywords) / len(required_keywords) * 100
        if required_keywords else 100.0
    )

    quantified_patterns = [
        r"\b\d+%\b",
        r"\b\d+[+]?\s*(?:users|customers|records|requests|projects|apis|tests)\b",
        r"\b(?:increased|decreased|improved|reduced|achieved|saved)\b.{0,50}\b\d+",
    ]
    quantified_count = sum(
        len(re.findall(pattern, lower_text))
        for pattern in quantified_patterns
    )
    has_quantified_results = quantified_count > 0

    action_verbs = [
        "developed", "built", "implemented", "designed", "created",
        "automated", "optimized", "deployed", "integrated", "tested",
        "analyzed", "improved", "develop", "build", "implement",
    ]
    action_verb_count = sum(
        len(re.findall(r"\b" + re.escape(v) + r"\b", lower_text))
        for v in action_verbs
    )

    section_score = sum(section_results.values()) / len(section_results) * 100
    contact_score = sum(contact_checks.values()) / len(contact_checks) * 100
    quantification_score = 100.0 if has_quantified_results else 40.0
    action_score = min(action_verb_count / 3, 1.0) * 100

    ats_score = (
        keyword_coverage * 0.40
        + section_score * 0.25
        + contact_score * 0.15
        + quantification_score * 0.10
        + action_score * 0.10
    )

    if ats_score >= 80:
        ats_status = "Strong ATS readiness"
    elif ats_score >= 60:
        ats_status = "Good ATS readiness"
    elif ats_score >= 40:
        ats_status = "Moderate ATS readiness"
    else:
        ats_status = "Needs ATS improvement"

    improvements = []
    missing_sections = [
        name for name, found in section_results.items() if not found
    ]
    if missing_sections:
        improvements.append(
            "Add clear standard sections: "
            + ", ".join(missing_sections[:3]) + "."
        )
    if missing_keywords:
        improvements.append(
            "Add relevant job keywords only where they accurately reflect "
            "your experience: " + ", ".join(missing_keywords[:5]) + "."
        )
    if not has_quantified_results:
        improvements.append(
            "Add measurable results to projects or experience, such as "
            "percentages, time saved, users served, or accuracy improvements."
        )
    if contact_score < 100:
        improvements.append(
            "Make sure your email, phone, LinkedIn, and GitHub are clearly "
            "visible if applicable."
        )
    if action_verb_count < 3:
        improvements.append(
            "Use strong action verbs such as built, implemented, automated, "
            "optimized, and deployed in project bullets."
        )

    return {
        "score": float(ats_score),
        "status": ats_status,
        "sections": section_results,
        "contact": contact_checks,
        "matched_keywords": matched_keywords,
        "missing_keywords": missing_keywords,
        "keyword_coverage": float(keyword_coverage),
        "has_quantified_results": has_quantified_results,
        "action_verb_count": action_verb_count,
        "improvements": improvements[:6],
    }


